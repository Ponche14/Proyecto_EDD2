    private void CrearCampoButtonFrameMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_CrearCampoButtonFrameMouseClicked
        String nombre = NombreCampoTextField.getText().trim();
        if (nombre.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(CrearCampoFrame, "El nombre del campo no puede estar vacio", "Error (No hay nombre)" , javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }
        char tipo;
        boolean esPrimaria = PrimariaCampoCheckBox.isSelected(); 
        boolean esSecundaria = SecundariaCampoCheckBox.isSelected();
        String nombreTipo = TipoCampoComboBox.getSelectedItem().toString();
        int longitud = 30; 

        switch (nombreTipo) {
            case "String":
                tipo = 'S';
                longitud = 30;
                break;
            case "Int":
                tipo = 'I';
                longitud = 4;
                break;
            case "Char":
                tipo = 'C';
                longitud = 2;
                break;
            case "Float":
                tipo = 'F';
                longitud = 8;
                break;
            default:
                tipo = '!';
                break;
        }

        Campo nuevoCampo = new Campo(nombre, tipo, longitud, esPrimaria, esSecundaria);
        dbms.getListaCampos().add(nuevoCampo);
        
        
        NombreCampoTextField.setText("");
        TipoCampoComboBox.setSelectedIndex(0);
        PrimariaCampoCheckBox.setSelected(false);
        SecundariaCampoCheckBox.setSelected(false);
        
        CrearCampoFrame.setVisible(false);
        ActualizarTablaCampos();
        
        javax.swing.JOptionPane.showMessageDialog(this, "¡Campo creado con exito!");
    }//GEN-LAST:event_CrearCampoButtonFrameMouseClicked

