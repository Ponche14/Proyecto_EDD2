    public void actualizarEstadoArchivo(String ruta){
        if (dbms.isArchivoAbierto() && ruta != null) {
            java.io.File f = new java.io.File(ruta);
            EstadoArchivoLabel.setText("Archivo activo: " + f.getName());
        }else{
            EstadoArchivoLabel.setText("Ningun archivo abierto");
        }
    }
    
    private void AbrirArchivoButtonMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_AbrirArchivoButtonMouseClicked
        javax.swing.JFileChooser selector = new javax.swing.JFileChooser();
        int resultado = selector.showOpenDialog(this);
        
        if(resultado == javax.swing.JFileChooser.APPROVE_OPTION) {
            String ruta = selector.getSelectedFile().getAbsolutePath();
            if (dbms.abrirArchivo(ruta)) {
                javax.swing.JOptionPane.showMessageDialog(this, "Archivo abierto correctamente.");
                actualizarEstadoArchivo(ruta);
            }else{
                javax.swing.JOptionPane.showMessageDialog(this, "Error al intentar abrir el archivo.");
                actualizarEstadoArchivo(null);
            }
        }
    }//GEN-LAST:event_AbrirArchivoButtonMouseClicked

    private void CerrarArchivoButtonMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_CerrarArchivoButtonMouseClicked
        if (dbms.isArchivoAbierto()) {
            if (dbms.cerrarArchivo()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Archivo cerrado de forma segura.");
                actualizarEstadoArchivo(null);
            }else{
                javax.swing.JOptionPane.showMessageDialog(this, "No se pudo cerrar el archivo.");
            }
        }else{
            javax.swing.JOptionPane.showMessageDialog(this, "No hay ningún archivo abierto actualmente.");
        }
    }//GEN-LAST:event_CerrarArchivoButtonMouseClicked

    private void CrearArchivoButtonMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_CrearArchivoButtonMouseClicked
        javax.swing.JFileChooser selector = new javax.swing.JFileChooser();
        int resultado = selector.showSaveDialog(this);
        
        if (resultado == javax.swing.JFileChooser.APPROVE_OPTION) {
            String ruta = selector.getSelectedFile().getAbsolutePath();
            if (dbms.crearArchivo(ruta)) {
                javax.swing.JOptionPane.showMessageDialog(this, "Archivo creado exitosamente.");
                actualizarEstadoArchivo(ruta);
            }else{
                javax.swing.JOptionPane.showMessageDialog(this, "Error al crear el archivo.");
                actualizarEstadoArchivo(null);
            }
        }
    }//GEN-LAST:event_CrearArchivoButtonMouseClicked

    private void GuardarArchivoButtonMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_GuardarArchivoButtonMouseClicked
        if (dbms.isArchivoAbierto()) {
            try {
                dbms.getMetadataActual().guardar(dbms.getArchivoActual());
                javax.swing.JOptionPane.showMessageDialog(this, "Cambios de la metadata guardados en disco duro.");
            } catch (java.io.IOException e) {
                javax.swing.JOptionPane.showMessageDialog(this, "Error crítico al escribir en el disco.");
            }
        }else{
            javax.swing.JOptionPane.showMessageDialog(this, "No hay ningun archivo abierto para guardar");
        }
    }//GEN-LAST:event_GuardarArchivoButtonMouseClicked

